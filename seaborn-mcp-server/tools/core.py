@mcp.tool()
def summarize_dataset(data: list[dict[str, Any]]) -> str:
    """
    Summarize a tabular dataset before plotting.

    The LLM should use this tool before choosing a visualization when it needs to inspect
    column names, data types, missing values, numeric summaries, category counts, or sample
    rows. This tool does not create a chart; it returns dataset metadata and descriptive
    statistics as JSON.
    """
    try:
        df = _df_from_records(data)

        return _to_json_string(
            {
                "status": "ok",
                "data_profile": _profile_dataframe(df),
                "numeric_summary": _describe_numeric(df),
                "sample_rows": _jsonable_records(df.head(20)),
                "warnings": [],
            }
        )

    except Exception as exc:
        return _to_json_string(
            {
                "status": "error",
                "error": str(exc),
                "warnings": [],
            }
        )


@mcp.tool()
def create_plot(
    request: dict[str, Any],
) -> str:
    """
    Create a statistical visualization using a generic request object.

    The LLM should use this tool when it already knows the desired chart kind and wants
    a single flexible interface. Supported kinds include scatter, line, histogram, kde,
    box, violin, bar, count, regression, residual, correlation_heatmap, pair, and facet.

    The response includes chart_json for LLM reasoning, interactive HTML (Plotly and/or
    seaborn mpld3), statistics, dataset profile, and warnings.
    """
    try:
        req = PlotRequest(**request)
        df = _df_from_records(req.data)
        return _to_json_string(_build_response(req, df))

    except Exception as exc:
        return _to_json_string(
            {
                "status": "error",
                "error": str(exc),
                "warnings": [],
            }
        )