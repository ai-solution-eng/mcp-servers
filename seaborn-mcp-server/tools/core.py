def _to_json_string(payload: dict[str, Any]) -> str:
    return json.dumps(
        payload,
        indent=2,
        ensure_ascii=False,
        default=str,
    )


def _infer_vegalite_type(df: pd.DataFrame, col: str) -> str:
    if pd.api.types.is_numeric_dtype(df[col]):
        return "quantitative"

    if pd.api.types.is_datetime64_any_dtype(df[col]):
        return "temporal"

    if pd.api.types.is_bool_dtype(df[col]):
        return "nominal"

    return "nominal"


def _to_chart_json(req: PlotRequest, df: pd.DataFrame) -> dict[str, Any]:
    encoding: dict[str, Any] = {}

    if req.x and req.x in df.columns:
        encoding["x"] = {
            "field": req.x,
            "type": _infer_vegalite_type(df, req.x),
        }

    if req.y and req.y in df.columns:
        encoding["y"] = {
            "field": req.y,
            "type": _infer_vegalite_type(df, req.y),
        }

    if req.hue and req.hue in df.columns:
        encoding["color"] = {
            "field": req.hue,
            "type": _infer_vegalite_type(df, req.hue),
        }

    if req.size and req.size in df.columns:
        encoding["size"] = {
            "field": req.size,
            "type": _infer_vegalite_type(df, req.size),
        }

    mark_by_kind = {
        "scatter": "point",
        "line": "line",
        "histogram": "bar",
        "kde": "area",
        "box": "boxplot",
        "violin": "density",
        "bar": "bar",
        "count": "bar",
        "regression": "point+line",
        "residual": "point",
        "correlation_heatmap": "rect",
        "pair": "matrix",
        "facet": "facet",
        "pie": "arc",
    }

    return {
        "$schema": "https://vega.github.io/schema/vega-lite/v5.json",
        "description": req.title
        or f"{req.kind} chart generated by statistical-visualization-mcp",
        "mark": mark_by_kind.get(req.kind, "point"),
        "encoding": encoding,
        "metadata": {
            "source_library": "seaborn",
        },
    }


def _build_plot_spec(req: PlotRequest) -> dict[str, Any]:
    return {
        "library": "seaborn",
        "kind": req.kind,
        "x": req.x,
        "y": req.y,
        "hue": req.hue,
        "size": req.size,
        "style": req.style,
        "row": req.row,
        "col": req.col,
        "title": req.title,
        "bins": req.bins,
    }


def _build_response(req: PlotRequest, df: pd.DataFrame) -> dict[str, Any]:
    warnings: list[str] = []

    missing = _validate_columns(
        df,
        [req.x, req.y, req.hue, req.size, req.style, req.row, req.col],
    )

    if missing:
        return {
            "status": "error",
            "kind": req.kind,
            "error": f"Missing columns: {missing}",
            "available_columns": df.columns.tolist(),
            "warnings": [],
        }

    plotly_html = None
    seaborn_mpld3_html = None

    try:
        plotly_html = _render_plotly_html(req, df)
    except Exception as exc:
        warnings.append(f"Could not render Plotly HTML: {exc}")

    try:
        seaborn_mpld3_html = _render_seaborn_html_mpld3(req, df)
    except Exception as exc:
        warnings.append(f"Could not render seaborn mpld3 HTML: {exc}")

    stats = _basic_stats(df, req.x, req.y, req.hue)

    if req.kind == "pie":
        try:
            pie_df = _prepare_pie_data(df, req.x, req.y)
            stats["pie_summary"] = _jsonable_records(pie_df)
        except Exception as exc:
            warnings.append(f"Could not compute pie summary: {exc}")

    return {
        "status": "ok",
        "kind": req.kind,
        "plot_spec": _build_plot_spec(req),
        "data_profile": _profile_dataframe(df),
        "stats": stats,
        "chart_json": _to_chart_json(req, df),
        "sampled_data": _jsonable_records(df.head(req.max_return_rows)),
        "html": {
            "plotly": plotly_html,
            "seaborn_mpld3": seaborn_mpld3_html,
        },
        "warnings": warnings,
    }


def _make_request(
    *,
    data: list[dict[str, Any]],
    kind: PlotKind,
    x: str | None = None,
    y: str | None = None,
    hue: str | None = None,
    size: str | None = None,
    style: str | None = None,
    row: str | None = None,
    col: str | None = None,
    title: str | None = None,
    bins: int | None = None,
    max_return_rows: int = 500,
) -> PlotRequest:
    return PlotRequest(
        data=data,
        kind=kind,
        x=x,
        y=y,
        hue=hue,
        size=size,
        style=style,
        row=row,
        col=col,
        title=title,
        bins=bins,
        max_return_rows=max_return_rows,
    )


